"""
Write components/shot-dimensions.ts from whatever the wall actually lists.

The wall is masonry: every tile keeps its plate's own ratio, so it has to know
that ratio before the image arrives. Without it the column reflows as each
shot decodes, and on a six-column `S` wall that is a visible jitter all the way
down.

Reading the files at render is not an option. This ships to Cloudflare Workers
through OpenNext, where there is no filesystem - see AGENTS.md - so the shapes
have to be a build-time fact, the same way pic-manifest.ts is.

Sources are the `src` strings in data/dossier.ts, not a directory glob, so the
manifest cannot contain shots the wall does not show and cannot miss one it
does. A src with no file on disk is an error here rather than a silent gap,
because the failure mode downstream is a blank tile.

Usage: python3 scripts/shot-dimensions.py
"""

from PIL import Image
import os
import re
import sys
import json

DATA = "data/dossier.ts"
OUT = "components/shot-dimensions.ts"


def main() -> int:
    body = open(DATA).read()
    match = re.search(r"  shots: \[\n(.*?)\n  \] as \{ src", body, re.S)
    if not match:
        print(f"{DATA}: no shots array found", file=sys.stderr)
        return 1

    srcs = re.findall(r'src: "([^"]+)"', match.group(1))
    dims = {}
    missing = []
    for src in srcs:
        path = os.path.join("public", src.lstrip("/"))
        if not os.path.exists(path):
            missing.append(src)
            continue
        with Image.open(path) as im:
            dims[src] = im.size

    if missing:
        for s in missing:
            print(f"missing file: {s}", file=sys.stderr)
        return 1

    dupes = len(srcs) - len(set(srcs))
    if dupes:
        print(f"{dupes} duplicate src in the shots array", file=sys.stderr)
        return 1

    with open(OUT, "w") as fh:
        fh.write(
            "/**\n"
            " * Intrinsic size of every study on the wall, as a build-time fact.\n"
            " *\n"
            " * GENERATED by scripts/shot-dimensions.py - do not edit by hand.\n"
            " *\n"
            " * The wall is masonry, so a tile needs its plate's ratio before the\n"
            " * image arrives; otherwise every column reflows as the shots decode.\n"
            " * Render cannot read these from disk - this ships to Cloudflare\n"
            " * Workers, where there is no filesystem - hence this file.\n"
            " */\n\n"
            "export const SHOT_DIMENSIONS: Record<string, [number, number]> = {\n"
        )
        for k in sorted(dims):
            fh.write(f"  {json.dumps(k)}: {json.dumps(list(dims[k]))},\n")
        fh.write("};\n")

    print(f"wrote {OUT}  ({len(dims)} shots)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
