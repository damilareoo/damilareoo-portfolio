"""
Write components/case-dimensions.ts from the frames the case studies list.

A case study is a long run of frames, each loading lazily. Without its shape
known up front a frame is zero pixels tall until it decodes, so every arrival
pushes the run below it down the page - the reading position jumps while the
visitor scrolls, and the rail's anchors drift. Knowing the ratio lets the page
hold each frame's box from the first paint.

Videos (.mp4, .mov, .webm) are measured by their poster, which is a still taken from the clip at
the clip's own size; Pillow cannot open an .mp4 and nothing else here needs
ffmpeg.

Same constraint as shot-dimensions.py: this ships to Cloudflare Workers, where
render has no filesystem, so the shapes are a build-time fact.

Usage: python3 scripts/case-dimensions.py
"""

from PIL import Image
import json
import os
import re
import sys

DATA = "data/dossier-work.ts"
OUT = "components/case-dimensions.ts"


def main() -> int:
    body = open(DATA).read()
    # Gallery entries are flat objects with no nested braces.
    entries = re.findall(r'\{\s*src: "(/dossier/[^"]+)"(.*?)\}', body, re.S)
    dims = {}
    missing = []
    for src, rest in entries:
        measured = src
        if src.endswith((".mp4", ".mov", ".webm")):
            poster = re.search(r'poster: "([^"]+)"', rest)
            if not poster:
                print(f"video with no poster: {src}", file=sys.stderr)
                return 1
            measured = poster.group(1)
        path = os.path.join("public", measured.lstrip("/"))
        if not os.path.exists(path):
            missing.append(measured)
            continue
        with Image.open(path) as im:
            dims[src] = im.size

    if missing:
        for s in missing:
            print(f"missing file: {s}", file=sys.stderr)
        return 1

    with open(OUT, "w") as fh:
        fh.write(
            "/**\n"
            " * Intrinsic size of every case-study frame, as a build-time fact.\n"
            " *\n"
            " * GENERATED by scripts/case-dimensions.py - do not edit by hand.\n"
            " *\n"
            " * Each frame holds its box before the file arrives, so a lazy image\n"
            " * landing mid-scroll cannot push the run below it down the page.\n"
            " * Videos carry their poster's size.\n"
            " */\n\n"
            "export const CASE_DIMENSIONS: Record<string, [number, number]> = {\n"
        )
        for k in sorted(dims):
            fh.write(f"  {json.dumps(k)}: {json.dumps(list(dims[k]))},\n")
        fh.write("};\n")

    print(f"wrote {OUT}  ({len(dims)} frames)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
